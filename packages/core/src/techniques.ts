export function techniqueById(id: string): Technique | undefined {
  return TECHNIQUES.find((technique) => technique.id === id);
}

export function techniquesOf(hand: "left" | "right"): Technique[] {
  return TECHNIQUES.filter((technique) => technique.hand === hand);
}
