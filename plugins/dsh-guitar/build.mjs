/**
 * 把 src/client.js 打成宿主能吃的形态：
 * 一个注册进 `window.__ModuleLoader__` 的 CJS 工厂，`require('react')` 由宿主提供。
 *
 * 不用 esbuild（沙箱里起不了子进程），用 rollup 的 JS API，纯 JS 可跑。
 */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { rollup } from "rollup";

const ENTRY = fileURLToPath(new URL("./src/client.js", import.meta.url));
const OUT = fileURLToPath(new URL("./client.js", import.meta.url));
const ID = "@local/guitar-lab";

const bundle = await rollup({ input: ENTRY, external: ["react"] });
const { output } = await bundle.generate({ format: "cjs", exports: "named" });

const chunk = output.find((item) => item.type === "chunk");
if (!chunk) throw new Error("rollup produced no chunk");

const body = chunk.code
  .split("\n")
  .map((line) => (line ? "    " + line : ""))
  .join("\n");

const wrapped = `/* generated by plugins/dsh-guitar/build.mjs — do not edit */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(ID)},
  factory(require) {
    const module = { exports: {} };
    const exports = module.exports;
${body}
    return module.exports;
  },
});
`;

await writeFile(OUT, wrapped, "utf8");
const size = (await readFile(OUT)).length;
console.log(`wrote client.js (${size} bytes)`);
