import fs from "node:fs";
import * as alphaTab from "@coderline/alphatab";
import { initSkia } from "./src/render.mjs";
initSkia();
const tex = "\\tempo 80\n\\ts (4 4)\n(3.5 2.4 0.3 1.2 0.1).8 {bd} (3.5{pm} 2.4{pm} 0.3{pm} 1.2{pm} 0.1{pm}).8 {bd} r.8 (3.5 2.4 0.3 1.2 0.1).8 {bd} 3.5.4 2.4.4 0.3.4 1.2.4 | (3.5 2.4 0.3 1.2 0.1).8 3.5.8 2.4.8 0.3.8 1.2.8 3.5.4 2.4.4 0.3.4";
const settings = new alphaTab.Settings();
settings.core.engine = "skia";
settings.core.logLevel = "error";
settings.display.scale = 1;
settings.display.layoutMode = alphaTab.LayoutMode.Page;
settings.notation.elements.set(alphaTab.NotationElement.EffectDynamics, false);
settings.notation.elements.set(alphaTab.NotationElement.EffectTempo, false);
settings.notation.elements.set(alphaTab.NotationElement.TrackNames, false);
settings.notation.elements.set(alphaTab.NotationElement.GuitarTuning, false);
settings.notation.extendLineEffectsToBeatEnd = true;
const score = alphaTab.importer.ScoreLoader.loadAlphaTex(tex, settings);
for (const t of score.tracks) for (const st of t.staves) { st.showTablature = true; st.showStandardNotation = false; st.tabConfig = { ...(st.tabConfig ?? {}), timeSignature: { isVisible: false }, barNumber: 2 }; }
const renderer = new alphaTab.rendering.ScoreRenderer(settings);
renderer.width = 600;
const parts = [];
renderer.partialLayoutFinished.on((a) => renderer.renderResult(a.id));
renderer.partialRenderFinished.on((a) => parts.push(a));
renderer.renderScore(score, [0]);
const canvas = new alphaTab.rendering.ScoreRenderer(settings).canvas;
